/** A page name from the client, folded into the prompt so the assistant can
 * stay relevant to what the driver is actually looking at. */
export function pageHint(page: string | undefined): string {
  const trimmed = (page ?? '').trim();
  return trimmed
    ? `Хэрэглэгч одоо аппын/кийоскийн «${trimmed}» хэсгээс асууж байна. Асуулт
тодорхойгүй бол энэ хэсэгтэй холбож хариул.`
    : '';
}
